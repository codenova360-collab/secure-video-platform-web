const root = join(
  import.meta.dirname,
  "..",
  "node_modules",
  "@material-symbols",
  "svg-400",
  "outlined",
);
const pathOf = (file) => {
  const svg = readFileSync(join(root, file), "utf8");
  const match = svg.match(/<path d="([^"]+)"/);
  if (!match) throw new Error(`No path in ${file}`);
  return match[1];
};

const lines = ICONS.sort().map((name) => {
  const outlined = pathOf(`${name}.svg`);
  const filled = pathOf(`${name}-fill.svg`);
  return `  ${name}: [${JSON.stringify(outlined)}, ${JSON.stringify(filled)}],`;
});

writeFileSync(
  join(import.meta.dirname, "..", "src", "components", "icons", "paths.ts"),
  `// Generated by scripts/generate-icons.mjs — do not edit.
// Material Symbols (Outlined, weight 400) © Google, Apache License 2.0.
// Each entry: [outlined path, filled path], viewBox "0 -960 960 960".

export const ICON_PATHS = {
${lines.join("\n")}
} as const;

export type IconName = keyof typeof ICON_PATHS;
`,
);
console.log(`Wrote ${ICONS.length} icons.`);
